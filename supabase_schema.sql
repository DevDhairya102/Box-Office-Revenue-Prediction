-- 1. Create Predictions Table
CREATE TABLE IF NOT EXISTS public.predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    movie_name TEXT NOT NULL,
    budget NUMERIC NOT NULL,
    runtime NUMERIC NOT NULL,
    primary_genre TEXT,
    lead_actor TEXT,
    director TEXT,
    production_company TEXT,
    release_year INTEGER,
    release_month INTEGER,
    vote_count INTEGER,
    popularity NUMERIC,
    predicted_revenue NUMERIC NOT NULL,
    roi NUMERIC
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.predictions ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow anonymous & authenticated users to read predictions
CREATE POLICY "Allow public read predictions"
    ON public.predictions
    FOR SELECT
    USING (true);

-- 4. Policy: Allow anonymous & authenticated users to insert predictions
CREATE POLICY "Allow public insert predictions"
    ON public.predictions
    FOR INSERT
    WITH CHECK (true);

-- 5. Create an index on created_at for fast retrieval of latest predictions
CREATE INDEX IF NOT EXISTS idx_predictions_created_at ON public.predictions (created_at DESC);
